-- Projeto físico do banco Cupcakes Gourmet (PostgreSQL 16).
-- SQL mantido portável para também rodar no H2 (MODE=PostgreSQL) usado nos testes.

CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100)  NOT NULL,
    email       VARCHAR(150)  NOT NULL,
    senha_hash  VARCHAR(100)  NOT NULL,
    telefone    VARCHAR(20),
    endereco    VARCHAR(255),
    papel       VARCHAR(20)   NOT NULL DEFAULT 'CLIENTE',
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_papel CHECK (papel IN ('CLIENTE', 'ADMIN'))
);

CREATE TABLE cupcake (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sabor       VARCHAR(80)   NOT NULL,
    descricao   VARCHAR(500),
    preco       NUMERIC(10,2) NOT NULL,
    estoque     INTEGER       NOT NULL DEFAULT 0,
    imagem_url  VARCHAR(255),
    ativo       BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cupcake_sabor UNIQUE (sabor),
    CONSTRAINT ck_cupcake_preco CHECK (preco > 0),
    CONSTRAINT ck_cupcake_estoque CHECK (estoque >= 0)
);

CREATE TABLE pedido (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        BIGINT        NOT NULL,
    data_hora         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status            VARCHAR(30)   NOT NULL,
    subtotal          NUMERIC(10,2) NOT NULL,
    frete             NUMERIC(10,2) NOT NULL,
    total             NUMERIC(10,2) NOT NULL,
    endereco_entrega  VARCHAR(255)  NOT NULL,
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_pedido_status CHECK (status IN
        ('AGUARDANDO_PAGAMENTO', 'PAGO', 'EM_PREPARO', 'ENVIADO', 'ENTREGUE', 'CANCELADO')),
    CONSTRAINT ck_pedido_valores CHECK (subtotal >= 0 AND frete >= 0 AND total = subtotal + frete)
);

CREATE INDEX ix_pedido_usuario ON pedido (usuario_id);
CREATE INDEX ix_pedido_status ON pedido (status);

CREATE TABLE item_pedido (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT        NOT NULL,
    cupcake_id       BIGINT        NOT NULL,
    quantidade       INTEGER       NOT NULL,
    preco_unitario   NUMERIC(10,2) NOT NULL,
    subtotal         NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_item_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_cupcake FOREIGN KEY (cupcake_id) REFERENCES cupcake (id),
    CONSTRAINT uk_item_pedido_cupcake UNIQUE (pedido_id, cupcake_id),
    CONSTRAINT ck_item_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_subtotal CHECK (subtotal = preco_unitario * quantidade)
);

CREATE INDEX ix_item_pedido_cupcake ON item_pedido (cupcake_id);

CREATE TABLE pagamento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT        NOT NULL,
    metodo         VARCHAR(20)   NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    valor          NUMERIC(10,2) NOT NULL,
    codigo_pix     VARCHAR(512),
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmado_em  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_pagamento_pedido UNIQUE (pedido_id),
    CONSTRAINT fk_pagamento_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    CONSTRAINT ck_pagamento_metodo CHECK (metodo IN ('PIX')),
    CONSTRAINT ck_pagamento_status CHECK (status IN ('PENDENTE', 'CONFIRMADO', 'CANCELADO')),
    CONSTRAINT ck_pagamento_valor CHECK (valor > 0)
);
